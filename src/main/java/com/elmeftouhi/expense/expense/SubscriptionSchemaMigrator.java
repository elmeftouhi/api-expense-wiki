package com.elmeftouhi.expense.expense;

import jakarta.annotation.PostConstruct;
import java.sql.Date;
import java.time.Instant;
import java.time.LocalDate;
import java.util.List;
import java.util.Map;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Component;

@Slf4j
@Component
@RequiredArgsConstructor
public class SubscriptionSchemaMigrator {

    private final JdbcTemplate jdbcTemplate;

    @PostConstruct
    public void migrate() {
        ensureExpenseColumns();
        ensureSubscriptionTables();
        ensureSubscriptionColumnTypes();
        backfillSubscriptionsFromLegacyTemplates();
        backfillOccurrenceHistoryAndExpenseLinks();
    }

    private void ensureSubscriptionColumnTypes() {
        // Some existing databases may already have a subscriptions table with bytea text fields.
        // Convert those columns to textual types so search queries using LOWER(...) remain valid.
        normalizeColumnTypeIfBytea("subscriptions", "name", "VARCHAR(200)");
        normalizeColumnTypeIfBytea("subscriptions", "description", "VARCHAR(500)");
        normalizeColumnTypeIfBytea("subscriptions", "currency", "VARCHAR(10)");
        normalizeColumnTypeIfBytea("subscriptions", "payment_method", "VARCHAR(100)");
        normalizeColumnTypeIfBytea("subscriptions", "notes", "VARCHAR(1000)");
    }

    private void ensureExpenseColumns() {
        addColumnIfMissing("expenses", "subscription_id", "BIGINT");
        addColumnIfMissing("expenses", "is_subscription_template", "BOOLEAN DEFAULT FALSE NOT NULL");

        tryExecute("CREATE INDEX IF NOT EXISTS idx_expenses_subscription_id ON expenses(subscription_id)");
        tryExecute("CREATE INDEX IF NOT EXISTS idx_expenses_template ON expenses(is_subscription_template)");
    }

    private void ensureSubscriptionTables() {
        tryExecute("""
                CREATE TABLE IF NOT EXISTS subscriptions (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    tenant_id BIGINT NOT NULL,
                    name VARCHAR(200) NOT NULL,
                    description VARCHAR(500),
                    category_id BIGINT NOT NULL,
                    owner_user_id BIGINT NOT NULL,
                    amount DECIMAL(19,2) NOT NULL,
                    currency VARCHAR(10) NOT NULL,
                    frequency VARCHAR(20) NOT NULL,
                    custom_interval_days INTEGER,
                    next_billing_date DATE NOT NULL,
                    end_date DATE,
                    status VARCHAR(20) NOT NULL,
                    reminder_lead_days INTEGER NOT NULL,
                    payment_method VARCHAR(100),
                    notes VARCHAR(1000),
                    anchor_day_of_month INTEGER NOT NULL,
                    anchor_month_of_year INTEGER NOT NULL,
                    legacy_template_expense_id BIGINT,
                    legacy_subscription_id BIGINT,
                    created_at TIMESTAMP NOT NULL,
                    updated_at TIMESTAMP,
                    version BIGINT NOT NULL DEFAULT 0
                )
                """);

        tryExecute("CREATE INDEX IF NOT EXISTS idx_subscriptions_v2_tenant_id ON subscriptions(tenant_id)");
        tryExecute("CREATE INDEX IF NOT EXISTS idx_subscriptions_v2_category_id ON subscriptions(category_id)");
        tryExecute("CREATE INDEX IF NOT EXISTS idx_subscriptions_v2_status ON subscriptions(status)");
        tryExecute("CREATE INDEX IF NOT EXISTS idx_subscriptions_v2_next_billing_date ON subscriptions(next_billing_date)");
        tryExecute("CREATE INDEX IF NOT EXISTS idx_subscriptions_v2_tenant_status_next_date ON subscriptions(tenant_id, status, next_billing_date)");
        tryExecute("CREATE INDEX IF NOT EXISTS idx_subscriptions_v2_legacy_expense_id ON subscriptions(legacy_template_expense_id)");
        tryExecute("CREATE INDEX IF NOT EXISTS idx_subscriptions_v2_legacy_subscription_id ON subscriptions(legacy_subscription_id)");

        tryExecute("""
                CREATE TABLE IF NOT EXISTS subscription_billing_occurrences (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    tenant_id BIGINT NOT NULL,
                    subscription_id BIGINT NOT NULL,
                    generated_expense_id BIGINT NOT NULL,
                    scheduled_billing_date DATE NOT NULL,
                    created_at TIMESTAMP NOT NULL,
                    CONSTRAINT uk_subscription_billing_occurrence_tenant_subscription_date
                        UNIQUE (tenant_id, subscription_id, scheduled_billing_date)
                )
                """);

        tryExecute("CREATE INDEX IF NOT EXISTS idx_subs_billing_occ_tenant_id ON subscription_billing_occurrences(tenant_id)");
        tryExecute("CREATE INDEX IF NOT EXISTS idx_subs_billing_occ_subscription_id ON subscription_billing_occurrences(subscription_id)");
        tryExecute("CREATE INDEX IF NOT EXISTS idx_subs_billing_occ_generated_expense ON subscription_billing_occurrences(generated_expense_id)");
        tryExecute("CREATE INDEX IF NOT EXISTS idx_subs_billing_occ_scheduled_date ON subscription_billing_occurrences(scheduled_billing_date)");

        tryExecute("""
                CREATE TABLE IF NOT EXISTS subscription_reminder_deliveries (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    tenant_id BIGINT NOT NULL,
                    subscription_id BIGINT NOT NULL,
                    scheduled_billing_date DATE NOT NULL,
                    user_id BIGINT NOT NULL,
                    channel VARCHAR(30) NOT NULL,
                    sent_at TIMESTAMP NOT NULL,
                    CONSTRAINT uk_subscription_reminder_delivery
                        UNIQUE (tenant_id, subscription_id, scheduled_billing_date, user_id, channel)
                )
                """);

        tryExecute("CREATE INDEX IF NOT EXISTS idx_subscription_reminder_tenant ON subscription_reminder_deliveries(tenant_id)");
        tryExecute("CREATE INDEX IF NOT EXISTS idx_subscription_reminder_subscription ON subscription_reminder_deliveries(subscription_id)");
        tryExecute("CREATE INDEX IF NOT EXISTS idx_subscription_reminder_date ON subscription_reminder_deliveries(scheduled_billing_date)");
    }

    private void backfillSubscriptionsFromLegacyTemplates() {
        List<Map<String, Object>> rows = queryRows("""
                SELECT es.id AS legacy_subscription_id,
                       es.tenant_id,
                       es.frequency,
                       es.custom_interval_days,
                       es.next_occurrence_date,
                       es.end_date,
                       es.is_active,
                       e.id AS template_expense_id,
                       e.category_id,
                       e.user_id,
                       e.description,
                       e.amount,
                       e.currency,
                       e.payment_method,
                       e.notes
                FROM expense_subscriptions es
                JOIN expenses e ON e.id = es.expense_id
                """);

        for (Map<String, Object> row : rows) {
            Long tenantId = longValue(row.get("tenant_id"));
            Long legacySubscriptionId = longValue(row.get("legacy_subscription_id"));

            if (existsLegacySubscription(tenantId, legacySubscriptionId)) {
                continue;
            }

            LocalDate nextBillingDate = localDateValue(row.get("next_occurrence_date"));
            if (nextBillingDate == null) {
                continue;
            }

            LocalDate endDate = localDateValue(row.get("end_date"));
            String frequency = stringValue(row.get("frequency"));
            String normalizedFrequency = "YEARLY".equalsIgnoreCase(frequency) ? "ANNUAL" : frequency;
            boolean active = booleanValue(row.get("is_active"));
            String description = stringValue(row.get("description"));

            jdbcTemplate.update(
                    """
                            INSERT INTO subscriptions (
                                tenant_id, name, description, category_id, owner_user_id, amount, currency,
                                frequency, custom_interval_days, next_billing_date, end_date, status,
                                reminder_lead_days, payment_method, notes, anchor_day_of_month,
                                anchor_month_of_year, legacy_template_expense_id, legacy_subscription_id,
                                created_at, updated_at, version
                            ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
                            """,
                    tenantId,
                    description != null && !description.isBlank() ? description : "Subscription #" + legacySubscriptionId,
                    description,
                    longValue(row.get("category_id")),
                    longValue(row.get("user_id")),
                    row.get("amount"),
                    stringValue(row.get("currency")),
                    normalizedFrequency,
                    row.get("custom_interval_days"),
                    Date.valueOf(nextBillingDate),
                    endDate != null ? Date.valueOf(endDate) : null,
                    active ? SubscriptionLifecycleStatus.ACTIVE.name() : SubscriptionLifecycleStatus.STOPPED.name(),
                    Subscription.DEFAULT_REMINDER_LEAD_DAYS,
                    stringValue(row.get("payment_method")),
                    stringValue(row.get("notes")),
                    nextBillingDate.getDayOfMonth(),
                    nextBillingDate.getMonthValue(),
                    longValue(row.get("template_expense_id")),
                    legacySubscriptionId,
                    Instant.now(),
                    Instant.now(),
                    0L
            );

            jdbcTemplate.update(
                    "UPDATE expenses SET is_subscription_template = TRUE WHERE tenant_id = ? AND id = ?",
                    tenantId,
                    longValue(row.get("template_expense_id"))
            );
        }
    }

    private void backfillOccurrenceHistoryAndExpenseLinks() {
        List<Map<String, Object>> rows = queryRows("""
                SELECT o.subscription_id AS legacy_subscription_id,
                       o.generated_expense_id,
                       o.occurrence_date,
                       es.tenant_id
                FROM subscription_occurrences o
                JOIN expense_subscriptions es ON es.id = o.subscription_id
                """);

        for (Map<String, Object> row : rows) {
            Long tenantId = longValue(row.get("tenant_id"));
            Long legacySubscriptionId = longValue(row.get("legacy_subscription_id"));
            Long generatedExpenseId = longValue(row.get("generated_expense_id"));
            LocalDate scheduledBillingDate = localDateValue(row.get("occurrence_date"));
            if (scheduledBillingDate == null) {
                continue;
            }

            Long subscriptionId = findNewSubscriptionId(tenantId, legacySubscriptionId);
            if (subscriptionId == null) {
                continue;
            }

            if (!existsOccurrence(tenantId, subscriptionId, scheduledBillingDate)) {
                jdbcTemplate.update(
                        """
                                INSERT INTO subscription_billing_occurrences (
                                    tenant_id, subscription_id, generated_expense_id, scheduled_billing_date, created_at
                                ) VALUES (?, ?, ?, ?, ?)
                                """,
                        tenantId,
                        subscriptionId,
                        generatedExpenseId,
                        Date.valueOf(scheduledBillingDate),
                        Instant.now()
                );
            }

            jdbcTemplate.update(
                    "UPDATE expenses SET subscription_id = ?, is_subscription_template = FALSE WHERE tenant_id = ? AND id = ?",
                    subscriptionId,
                    tenantId,
                    generatedExpenseId
            );
        }
    }

    private boolean existsLegacySubscription(Long tenantId, Long legacySubscriptionId) {
        Integer count = jdbcTemplate.queryForObject(
                "SELECT COUNT(*) FROM subscriptions WHERE tenant_id = ? AND legacy_subscription_id = ?",
                Integer.class,
                tenantId,
                legacySubscriptionId
        );
        return count != null && count > 0;
    }

    private Long findNewSubscriptionId(Long tenantId, Long legacySubscriptionId) {
        List<Long> ids = jdbcTemplate.query(
                "SELECT id FROM subscriptions WHERE tenant_id = ? AND legacy_subscription_id = ?",
                (rs, rowNum) -> rs.getLong(1),
                tenantId,
                legacySubscriptionId
        );
        return ids.isEmpty() ? null : ids.get(0);
    }

    private boolean existsOccurrence(Long tenantId, Long subscriptionId, LocalDate scheduledBillingDate) {
        Integer count = jdbcTemplate.queryForObject(
                """
                        SELECT COUNT(*) FROM subscription_billing_occurrences
                        WHERE tenant_id = ? AND subscription_id = ? AND scheduled_billing_date = ?
                        """,
                Integer.class,
                tenantId,
                subscriptionId,
                Date.valueOf(scheduledBillingDate)
        );
        return count != null && count > 0;
    }

    private void addColumnIfMissing(String tableName, String columnName, String columnDefinition) {
        if (columnExists(tableName, columnName)) {
            return;
        }
        tryExecute("ALTER TABLE " + tableName + " ADD COLUMN " + columnName + " " + columnDefinition);
    }

    private void normalizeColumnTypeIfBytea(String tableName, String columnName, String targetType) {
        String dataType = getColumnDataType(tableName, columnName);
        if (dataType == null || !"bytea".equalsIgnoreCase(dataType)) {
            return;
        }

        tryExecute(
                "ALTER TABLE " + tableName
                        + " ALTER COLUMN " + columnName
                        + " TYPE " + targetType
                        + " USING encode(" + columnName + ", 'escape')"
        );
    }

    private boolean columnExists(String tableName, String columnName) {
        try {
            Integer count = jdbcTemplate.queryForObject(
                    """
                            SELECT COUNT(*)
                            FROM INFORMATION_SCHEMA.COLUMNS
                            WHERE LOWER(TABLE_NAME) = LOWER(?)
                              AND LOWER(COLUMN_NAME) = LOWER(?)
                            """,
                    Integer.class,
                    tableName,
                    columnName
            );
            return count != null && count > 0;
        } catch (Exception ex) {
            return false;
        }
    }

    private String getColumnDataType(String tableName, String columnName) {
        try {
            return jdbcTemplate.queryForObject(
                    """
                            SELECT data_type
                            FROM INFORMATION_SCHEMA.COLUMNS
                            WHERE LOWER(TABLE_NAME) = LOWER(?)
                              AND LOWER(COLUMN_NAME) = LOWER(?)
                            LIMIT 1
                            """,
                    String.class,
                    tableName,
                    columnName
            );
        } catch (Exception ex) {
            return null;
        }
    }

    private List<Map<String, Object>> queryRows(String sql) {
        try {
            return jdbcTemplate.queryForList(sql);
        } catch (Exception ex) {
            return List.of();
        }
    }

    private void tryExecute(String sql) {
        try {
            jdbcTemplate.execute(sql);
        } catch (Exception ex) {
            log.debug("Schema statement skipped: {}", sql, ex);
        }
    }

    private Long longValue(Object value) {
        if (value == null) {
            return null;
        }
        if (value instanceof Number number) {
            return number.longValue();
        }
        return Long.parseLong(value.toString());
    }

    private String stringValue(Object value) {
        return value != null ? value.toString() : null;
    }

    private LocalDate localDateValue(Object value) {
        if (value == null) {
            return null;
        }
        if (value instanceof LocalDate localDate) {
            return localDate;
        }
        if (value instanceof Date date) {
            return date.toLocalDate();
        }
        return LocalDate.parse(value.toString());
    }

    private boolean booleanValue(Object value) {
        if (value == null) {
            return false;
        }
        if (value instanceof Boolean bool) {
            return bool;
        }
        return Boolean.parseBoolean(value.toString());
    }
}

